/** Линии ушей (индексы в LINES) и точки, вокруг которых они поворачиваются вслед за ушами куклы. */
const FAR_EAR = { lines: [0, 1], pivot: [150, 92] as const }
const NEAR_EAR = { lines: [2, 3], pivot: [236, 125] as const }

let cache: { sil: Path2D[]; lines: [Path2D, string, number][]; nose: Path2D } | null = null
function paths(): NonNullable<typeof cache> {
  if (!cache) {
    cache = {
      sil: SILHOUETTE.map((d) => new Path2D(d)),
      lines: LINES.map(([d, c, w]) => [new Path2D(d), c, w]),
      nose: new Path2D(NOSE)
    }
  }
  return cache
}

/** Перевести контекст в систему рисунка; breath — дыхание: спина чуть поднимается и опускается (от земли). */
function place(c: CanvasRenderingContext2D, breath: number): void {
  const p = SLEEP_ART_PLACE
  c.translate(p.x, p.ground)
  c.scale(p.scale * (1 - breath * 0.002), p.scale * (1 + breath * 0.009))
  c.translate(-p.left, -p.bottom)
}

/** Повернуть вокруг точки (ухо «долетает»). */
function turnAbout(c: CanvasRenderingContext2D, [px, py]: readonly [number, number], a: number): void {
  if (Math.abs(a) < 1e-4) return
  c.translate(px, py)
  c.rotate(a)
  c.translate(-px, -py)
}

/** Силуэт спящего — в слой силуэта (по нему рисуется светлая кайма на тёмном столе). */
export function drawSleepArtSilhouette(c: CanvasRenderingContext2D, color: string, breath: number): void {
  const { sil } = paths()
  c.save()
  place(c, breath)
  c.fillStyle = color
  for (const p of sil) c.fill(p)
  c.restore()
}

/**
 * Контур, линии, глаза, усы и нос спящего — поверх силуэта. lagFar/lagNear — насколько уши куклы сейчас
 * отклонены от покоя (рад; уши на пружине) — линии ушей поворачиваются вместе с ними.
 */
export function drawSleepArtDetails(c: CanvasRenderingContext2D, ink: string, breath: number, lagFar = 0, lagNear = 0): void {
  const { sil, lines, nose } = paths()
  c.save()
  place(c, breath)
  c.lineCap = 'round'
  c.lineJoin = 'round'
  // как в рисунке: хвостик с контуром, поверх — тело (закрывает край хвостика у тела), потом контур тела.
  // Цвет — ровный цвет нашего кролика (в рисунке был лёгкий градиент — голова и тело выходили разного тона)
  sil.forEach((p, i) => {
    if (i > 0) {
      c.fillStyle = ink
      c.fill(p)
    }
    c.strokeStyle = OUTLINE[i][0]
    c.lineWidth = OUTLINE[i][1]
    c.stroke(p)
  })
  lines.forEach(([p, color, w], i) => {
    c.save()
    if (FAR_EAR.lines.includes(i)) turnAbout(c, FAR_EAR.pivot, lagFar)
    if (NEAR_EAR.lines.includes(i)) turnAbout(c, NEAR_EAR.pivot, lagNear)
    c.strokeStyle = color
    c.lineWidth = w
    c.stroke(p)
    c.restore()
  })
  const g = c.createLinearGradient(94, 223.74, 94, 244)
  g.addColorStop(0, '#FFB2B7')
  g.addColorStop(1, '#ED909C')
  c.fillStyle = g
  c.fill(nose)
  c.strokeStyle = '#121214'
  c.lineWidth = 1.3
  c.stroke(nose)
  c.restore()
}
